// gte_state.h — one GTE (COP2) register file, so two Cores run with separate GTE state. Beetle's gte.c works on
// the file psx::cpu::Gte binds before each call.
#pragma once
#include <stdint.h>

// A projected point's screen position before RTPS/RTPT truncate it into an SXY word, and the view depth it was
// divided by (Beetle's SZ3, at least H/2); depth 0 for a point no projection made. `back`: view units its polygon's
// draw site sorts it back by, which only the depth that polygon leaves for later draws carries.
typedef struct GtePlace {
  float x;
  float y;
  float z;
  float back;
} GtePlace;

// The depth unit of the translation the guest last loaded: a draw site tagged the TRZ word it was loaded from
// (VertexPlaces), so projections under it are SZ times `scale`, less `nearer`, in the title's common view units.
// `carried` is 0 for a translation from anywhere else.
typedef struct GteTranslationDepth {
  float scale;
  float nearer;
  uint32_t carried;
} GteTranslationDepth;

typedef struct GteRegs {
  uint32_t REG[64];  // DR = REG[0..31] (data regs), CR = REG[32..63] (control regs)
  uint32_t FLAGS;    // overflow flags generated by GTE commands
  uint32_t *CR, *DR; // point into REG (REG+32 / REG); (re)set by GTE_BindState
  // The unrounded place of each SXY FIFO entry, shifted with it by every projection push.
  GtePlace places[3];
  GteTranslationDepth translationDepth;
} GteRegs;

// The whole GTE copied passively. Reading DR12..DR14 pops the projection FIFO and reading a flag register
// clears the flag, so a snapshot built from register reads would hand the guest back a GTE that had run.
typedef struct GteRawState {
  uint32_t reg[64]; // DR = reg[0..31], CR = reg[32..63]
  uint32_t flags;   // the accumulated overflow flags
  GtePlace places[3];
  GteTranslationDepth translationDepth;
} GteRawState;
