#!/usr/bin/env python3
"""Compile the fixed SDL_GPU shader set to an embedded SPIR-V header.

The C array names are an ABI with runtime/psx/render.  Shared ``.glsl`` includes are
dependencies, not entry points; ``record_op.glsl`` is written beside the header from the
op layout in record_raster_setup.h.
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

SHADER_DIR_REL = Path("runtime/psx/shaders_gpu")
OP_LAYOUT_RELS = (Path("runtime/psx/gpu/record_raster_setup.h"), Path("runtime/psx/present/vram_rect.h"))
OP_LAYOUT_NAME = "record_op.glsl"
SHADERS = (
    ("fullscreen.vert", "spv_g_fullscreen_vert"),
    ("present.frag", "spv_g_present_frag"),
    ("image.frag", "spv_g_image_frag"),
    ("rml.vert", "spv_g_rml_vert"),
    ("rml.frag", "spv_g_rml_frag"),
    ("pane.vert", "spv_g_pane_vert"),
    ("pane.frag", "spv_g_pane_frag"),
    ("record.vert", "spv_g_record_vert"),
    ("record.frag", "spv_g_record_frag"),
)


class GeneratorError(RuntimeError):
    """A user-facing generator failure without a Python traceback."""


def find_glslc(search_path: str | None = None) -> str:
    glslc = shutil.which("glslc", path=search_path)
    if glslc is None:
        raise GeneratorError("glslc not found (install the Vulkan SDK)")
    return glslc


def dependency_paths(root: Path, tool_path: Path) -> list[Path]:
    shader_dir = root / SHADER_DIR_REL
    dependencies = [tool_path, *(root / rel for rel in OP_LAYOUT_RELS)]
    for suffix in ("*.vert", "*.frag", "*.glsl"):
        dependencies.extend(shader_dir.glob(suffix))
    return dependencies


def path_is_current(path: Path, dependencies: list[Path]) -> bool:
    if not path.is_file() or not dependencies:
        return False
    path_mtime = path.stat().st_mtime_ns
    return all(path_mtime > dependency.stat().st_mtime_ns for dependency in dependencies)


def integer_value(expression: str, known: dict[str, int]) -> int:
    """An integer expression such as ``1u << 8`` or ``1 + kRecordMaxCanvases``."""
    tree = ast.parse(re.sub(r"(?<=[0-9a-fA-F])u\b", "", expression), mode="eval")
    allowed = (ast.Expression, ast.BinOp, ast.Constant, ast.Name, ast.Load, ast.LShift, ast.BitOr, ast.Add, ast.Sub, ast.Mult)
    if not all(isinstance(node, allowed) for node in ast.walk(tree)):
        raise GeneratorError(f"op layout value is not an integer expression: {expression}")
    try:
        return int(eval(compile(tree, "<op layout>", "eval"), {"__builtins__": {}}, known))
    except NameError as error:
        raise GeneratorError(f"op layout value names an unknown constant: {expression}") from error


def op_layout_glsl(root: Path) -> str:
    """The op layout's constants as GLSL: ints stay int, enumerators become uint."""
    lines = ["// GENERATED by tools/gen_gpu_shaders.py from record_raster_setup.h and vram_rect.h.\n"]
    known: dict[str, int] = {}
    for rel in reversed(OP_LAYOUT_RELS):
        text = re.sub(r"//[^\n]*", "", (root / rel).read_text(encoding="utf-8"))
        for name, value in re.findall(r"inline constexpr int (\w+) = ([^;]+);", text):
            known[name] = integer_value(value, known)
            lines.append(f"const int {name} = {known[name]};\n")
        for scoped, enum_name, body in re.findall(r"enum (class )?(\w+)\s*:\s*[\w:]+\s*\{([^}]*)\}", text):
            for entry in body.split(","):
                if "=" not in entry:
                    continue
                name, value = (part.strip() for part in entry.split("=", 1))
                glsl_name = f"k{enum_name}{name}" if scoped else name
                known[name] = integer_value(value, known)
                lines.append(f"const uint {glsl_name} = {known[name]}u;\n")
    return "".join(lines)


def compile_shader(glslc: str, include_dirs: list[Path], shader_dir: Path, source_name: str, output: Path) -> None:
    command = [glslc]
    for include_dir in include_dirs:
        command += ["-I", str(include_dir)]
    command += [str(shader_dir / source_name), "-o", str(output)]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        suffix = f"\n{detail}" if detail else ""
        raise GeneratorError(f"glslc failed for {source_name} (exit {result.returncode}){suffix}")
    if result.stdout:
        sys.stdout.write(result.stdout)
    if result.stderr:
        sys.stderr.write(result.stderr)


def spirv_array(path: Path, array_name: str) -> str:
    data = path.read_bytes()
    if len(data) % 4 != 0:
        raise GeneratorError(f"{path.name}: SPIR-V not word-aligned")
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = [f"static const uint32_t {array_name}[] = {{"]
    for start in range(0, len(words), 8):
        chunk = ", ".join(f"0x{word:08x}" for word in words[start : start + 8])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append(f"static const unsigned {array_name}_len = sizeof({array_name});")
    return "\n".join(lines) + "\n"


def generate(
    root: Path,
    glslc: str,
    *,
    output: Path,
    tool_path: Path | None = None,
    stamp: Path | None = None,
    announce: bool = True,
) -> bool:
    tool_path = tool_path or Path(__file__).resolve()
    shader_dir = root / SHADER_DIR_REL
    dependencies = dependency_paths(root, tool_path)
    freshness_owner = stamp or output
    if output.is_file() and path_is_current(freshness_owner, dependencies):
        return False

    missing = [source for source, _array in SHADERS if not (shader_dir / source).is_file()]
    if missing:
        raise GeneratorError("missing shader source(s): " + ", ".join(missing))

    output.parent.mkdir(parents=True, exist_ok=True)
    op_layout = output.parent / OP_LAYOUT_NAME
    op_layout_text = op_layout_glsl(root)
    if not op_layout.is_file() or op_layout.read_text(encoding="utf-8") != op_layout_text:
        op_layout.write_text(op_layout_text, encoding="utf-8")
    with tempfile.TemporaryDirectory(prefix="gen_gpu_shaders-", dir=output.parent) as temp_name:
        temp_dir = Path(temp_name)
        header = [
            "// GENERATED by tools/gen_gpu_shaders.py — do not edit. SPIR-V for the SDL_GPU renderer.\n",
            "#include <stdint.h>\n",
        ]
        for source_name, array_name in SHADERS:
            spv_path = temp_dir / f"{source_name}.spv"
            compile_shader(glslc, [shader_dir, output.parent], shader_dir, source_name, spv_path)
            header.append(spirv_array(spv_path, array_name))
        temp_header = temp_dir / output.name
        temp_header.write_text("".join(header), encoding="utf-8")
        header_changed = not output.is_file() or temp_header.read_bytes() != output.read_bytes()
        if header_changed:
            os.replace(temp_header, output)

    if stamp is not None:
        stamp.parent.mkdir(parents=True, exist_ok=True)
        stamp.touch()

    if announce:
        if header_changed:
            print(f"[gen_gpu_shaders] wrote {output}")
        else:
            print("[gen_gpu_shaders] shader bytes unchanged; refreshed dependency stamp")
    return header_changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        help="generated header path owned by this consumer build tree",
    )
    parser.add_argument(
        "--stamp",
        type=Path,
        help="CMake dependency stamp; updated only after every shader compiles successfully",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    try:
        if args.output is None:
            raise GeneratorError("--output is required")
        stamp = args.stamp
        if stamp is None:
            stamp = root / "scratch/gen_gpu_shaders.stamp"
        generate(root, find_glslc(), output=args.output, stamp=stamp)
    except GeneratorError as error:
        print(f"gen_gpu_shaders: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
